#!/usr/bin/env python3
"""Build fully self-contained Polish narrated micro-lessons for GitHub Pages.
Generated by a local, open-source synthetic TTS (eSpeak); no external audio service.
"""
from pathlib import Path
import json, math, re, subprocess, wave
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parent.parent
TEXT=(ROOT/'course-guided.js').read_text(encoding='utf-8')
m=re.search(r'const DATA=(.*?);\nconst mk=',TEXT,re.S)
if not m: raise RuntimeError('Guided script data missing')
DATA=json.loads(m.group(1))
OUT=ROOT/'assets'/'videos';OUT.mkdir(parents=True,exist_ok=True)
FONT='/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
BOLD='/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
f=lambda n,b=False: ImageFont.truetype(BOLD if b else FONT,n)
W,H,FPS=960,540,6
TOPICS={
'ai-ml':'guide-ml','llm':'guide-llm','rag-azure':'guide-rag',
'fine-tuning':'guide-finetune','agenci':'guide-agents','produkcja':'guide-mlops'}
TITLES={
'ai-ml':'Uczenie maszynowe: pełny cykl',
'llm':'LLM: od tokenu do tekstu',
'rag-azure':'RAG: dokumenty i odpowiedź',
'fine-tuning':'Fine-tuning: gradient i adapter',
'agenci':'Agentic AI: narzędzia i decyzje',
'produkcja':'MLOps: od eksperymentu do wdrożenia'}
def say(text,path):
 subprocess.run(['espeak','-v','pl','-s','156','-a','145','-w',str(path),text],check=True,stdout=subprocess.DEVNULL)
 with wave.open(str(path),'rb') as wav:return wav.getnframes()/wav.getframerate()
def lines(draw,text,font,maxwidth):
 result=[]
 for part in text.split('\n'):
  ln=''
  for word in part.split():
   test=(ln+' '+word).strip()
   if draw.textbbox((0,0),test,font=font)[2] > maxwidth and ln:
    result.append(ln);ln=word
   else:ln=test
  if ln:result.append(ln)
 return result
def framebase(topic,steps,step):
 s=steps[step];im=Image.new('RGB',(W,H),'#081728');d=ImageDraw.Draw(im)
 d.rounded_rectangle((15,15,945,525),radius=22,fill='#10273b',outline='#3f6677',width=2)
 d.text((36,28),'ENTERPRISE AI ACADEMY  /  POLSKI LEKTOR',font=f(14,True),fill='#76e4d1')
 d.text((36,55),TITLES[topic],font=f(28,True),fill='#f6fbff')
 d.text((36,101),'Przejdź od wejścia przez obliczenia do wyjścia / INPUT → PROCESS → OUTPUT',font=f(14),fill='#c7d9e7')
 d.line((36,134,923,134),fill='#35586c',width=2)
 d.rounded_rectangle((36,151,924,199),radius=11,fill='#173e4c')
 d.text((52,163),f'{step+1:02d} / {len(steps):02d}  {s[0]}  |  {s[1]}',font=f(19,True),fill='#89ead7')
 for j,st in enumerate(steps):
  x=37+j*179
  d.rounded_rectangle((x,488,x+161,510),radius=7,fill='#70d8c7' if j<=step else '#2c475a')
  d.text((x+75,490),str(j+1),font=f(12,True),fill='#061624' if j<=step else '#b9cbd7')
 # on-screen narration text, not only a chart
 blocks=[('CO SIĘ DZIEJE? / WHAT?',s[2]),('DLACZEGO? / WHY?',s[3]),('WEJŚCIE / INPUT:',s[4]),('WYJŚCIE / OUTPUT:',s[5])]
 y=213
 for title,body in blocks:
  d.text((40,y),title,font=f(12,True),fill='#fbd18b')
  y+=18
  for row in lines(d,body,f(17),520):
   d.text((40,y),row,font=f(17),fill='#f5faff');y+=22
  y+=10
  if y>459:break
 # visual operation shows the real stage inputs -> transformation -> output
 d.rounded_rectangle((610,226,919,442),radius=12,fill='#0b2031',outline='#476b7e')
 for j,(label,value) in enumerate([('INPUT',s[4]),('PROCESS',s[0]),('OUTPUT',s[5])]):
  yy=237+j*69
  d.rounded_rectangle((624,yy,903,yy+48),radius=9,fill=['#12344b','#184551','#20564e'][j],outline='#5d9c9f')
  d.text((634,yy+5),label,font=f(11,True),fill='#fbd18b')
  textrows=lines(d,value,f(13),250)
  d.text((634,yy+23),textrows[0] if textrows else '-',font=f(13),fill='#eff9ff')
  if j!=2:d.text((762,yy+49),'↓',font=f(14,True),fill='#76e4d1')
 return im
def build(topic,base):
 steps=DATA[topic];work=OUT/('.build-'+base);work.mkdir(exist_ok=True)
 durations=[];wavs=[]
 for i,s in enumerate(steps):
  wav=work/f'{i}.wav'
  duration=say(s[0]+'. '+s[2]+' Dlaczego? '+s[3]+' Wejście: '+s[4]+'. Wyjście: '+s[5]+'. Przykład: '+s[6],wav)
  durations.append(duration+.4);wavs.append(wav)
 inp=sum((['-i',str(w)] for w in wavs),[])
 filtercomplex=';'.join(f'[{i}:a]apad=pad_dur=0.4[a{i}]' for i in range(len(wavs)))
 filtercomplex+=';'+''.join(f'[a{i}]' for i in range(len(wavs)))+f'concat=n={len(wavs)}:v=0:a=1[all]'
 sound=work/'sound.wav'
 subprocess.run(['ffmpeg','-v','error','-y',*inp,'-filter_complex',filtercomplex,'-map','[all]',str(sound)],check=True)
 with wave.open(str(sound),'rb') as w:total=w.getnframes()/w.getframerate()
 counts=[round(d*FPS) for d in durations];counts[-1]+=round(total*FPS)-sum(counts)
 slides=[framebase(topic,steps,i) for i in range(len(steps))]
 cmd=['ffmpeg','-v','error','-y','-f','rawvideo','-pixel_format','rgb24','-video_size',f'{W}x{H}',
      '-framerate',str(FPS),'-i','-','-i',str(sound),'-c:v','libx264','-preset','veryfast',
      '-crf','28','-pix_fmt','yuv420p','-c:a','aac','-b:a','72k','-movflags','+faststart',
      '-shortest',str(OUT/(base+'.mp4'))]
 proc=subprocess.Popen(cmd,stdin=subprocess.PIPE)
 try:
  for i,slide in enumerate(slides):
   for n in range(max(1,counts[i])):
    pic=slide.copy();d=ImageDraw.Draw(pic)
    d.rounded_rectangle((38,518,923,523),radius=2,fill='#365569')
    d.rounded_rectangle((38,518,38+round(885*n/max(1,counts[i])),523),radius=2,fill='#7be5d1')
    d.ellipse((906-6*(n%4),162,915-6*(n%4),171),fill='#fbd18b')
    proc.stdin.write(pic.tobytes())
 finally:proc.stdin.close()
 if proc.wait():raise RuntimeError('ffmpeg failed')
 for fpath in work.iterdir():fpath.unlink()
 work.rmdir()
 print(base,'built',round(total,1),'seconds',flush=True)
for topic,basename in TOPICS.items():build(topic,basename)
